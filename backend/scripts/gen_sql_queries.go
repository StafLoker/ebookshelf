//go:build ignore

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const namePrefix = "-- Name:"

func main() {
	var b strings.Builder

	files, err := filepath.Glob("queries/*.sql")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	b.WriteString("// Code generated by gen_sql_queries.go; DO NOT EDIT.\n\npackage repository\n\nvar (\n")
	for _, file := range files {
		content, err := os.ReadFile(file)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		entity := strings.TrimSuffix(filepath.Base(file), ".sql")
		words := strings.Split(entity, "_")
		for i := 1; i < len(words); i++ {
			words[i] = strings.ToUpper(words[i][:1]) + words[i][1:]
		}
		entity = strings.Join(words, "")
		for _, block := range strings.Split(string(content), namePrefix)[1:] {
			name, body, _ := strings.Cut(block, "\n")
			fmt.Fprintf(&b, "\t%s%s = `\n%s\n`\n", entity, strings.TrimSpace(name), strings.TrimSpace(body))
		}
	}
	b.WriteString(")\n")

	if err := os.WriteFile("queries.go", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("Generated queries.go")
}
